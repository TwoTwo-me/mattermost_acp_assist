#!/usr/bin/env python3
"""Collect upstream Cargo dependency notices for every published native target."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
TARGETS = (
    "x86_64-unknown-linux-gnu",
    "aarch64-unknown-linux-gnu",
    "x86_64-apple-darwin",
    "aarch64-apple-darwin",
)
NOTICE_NAME = re.compile(r"^(?:licen[cs]e|unlicense|copying|copyright|notices?)(?:$|[._-])", re.IGNORECASE)
SOURCE_SUFFIXES = {".c", ".h", ".rs", ".s", ".asm", ".pl", ".py", ".sh"}


def dependency_packages():
    packages = {}
    targets = {}
    for target in TARGETS:
        metadata = json.loads(subprocess.check_output([
            "cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", target,
        ], cwd=ROOT, text=True))
        root = metadata["resolve"]["root"]
        nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
        available = {package["id"]: package for package in metadata["packages"]}
        pending = [root]
        visited = set()
        while pending:
            package_id = pending.pop()
            if package_id in visited:
                continue
            visited.add(package_id)
            pending.extend(
                dependency["pkg"] for dependency in nodes[package_id]["deps"]
                if any(kind["kind"] != "dev" for kind in dependency["dep_kinds"])
            )
        for package_id in visited - {root}:
            packages[package_id] = available[package_id]
            targets.setdefault(package_id, []).append(target)
    return packages, targets


def ring_source_header(path):
    if path.suffix.lower() not in SOURCE_SUFFIXES:
        return None
    hash_comments = path.suffix.lower() in {".pl", ".py", ".sh", ".s"}
    lines = []
    block_comment = False
    for line in path.read_text(encoding="utf-8").splitlines(keepends=True):
        stripped = line.lstrip()
        if block_comment:
            lines.append(line)
            block_comment = "*/" not in line
        elif not stripped.strip() or stripped.startswith("//"):
            lines.append(line)
        elif stripped.startswith("/*"):
            lines.append(line)
            block_comment = "*/" not in line
        elif hash_comments and stripped.startswith("#"):
            lines.append(line)
        elif path.suffix.lower() == ".asm" and stripped.startswith(";"):
            lines.append(line)
        else:
            break
    header = "".join(lines).rstrip()
    if "copyright" in header.lower():
        return header
    return None


def render_notices():
    packages, targets = dependency_packages()
    lock_hash = hashlib.sha256((ROOT / "Cargo.lock").read_bytes()).hexdigest()
    sections = [
        "Third-party Cargo dependency license and attribution notices\n",
        "Generated by python3 scripts/generate-notices.py. Do not edit by hand.\n",
        f"Cargo.lock SHA256: {lock_hash}\n",
        "\nTargets:\n" + "\n".join(TARGETS) + "\n",
        "\nThis is the conservative normal/build dependency closure of Cargo.lock for these\n"
        "targets. It may include build-only or unused target-conditional dependencies.\n"
        "Upstream license, copyright and NOTICE files are reproduced in full, including\n"
        "alternative licenses. ring source headers are included where its LICENSE directs\n"
        "readers to per-file notices. Paths below are relative to upstream crate sources.\n"
        "The application itself is excluded. This file does not grant a license to the\n"
        "application. Rust runtime notices are appended by the release packager using\n"
        "the same installed toolchain that built the binary. Node adapters are installed\n"
        "separately by npm and are not bundled in the native release archive.\n",
    ]
    for package_id, package in sorted(packages.items(), key=lambda item: (item[1]["name"], item[1]["version"])):
        directory = Path(package["manifest_path"]).parent
        paths = sorted(path for path in directory.rglob("*") if path.is_file() and NOTICE_NAME.match(path.name))
        if package["license_file"]:
            declared = directory / package["license_file"]
            if not declared.is_file():
                raise RuntimeError(f"missing declared license file for {package['name']} {package['version']}")
            declared.resolve().relative_to(directory.resolve())
            if declared not in paths:
                paths.append(declared)
                paths.sort()
        if not paths:
            raise RuntimeError(f"no upstream license files found for {package['name']} {package['version']}")
        sections.append(
            f"\n{'=' * 78}\n{package['name']} {package['version']}\n"
            f"Declared license expression: {package['license'] or 'see upstream files'}\n"
            f"Targets: {', '.join(targets[package_id])}\n"
        )
        for path in paths:
            text = path.read_text(encoding="utf-8")
            if not text.strip():
                raise RuntimeError(f"empty upstream notice: {package['name']} {path.relative_to(directory)}")
            sections.append(f"\n--- {path.relative_to(directory).as_posix()} ---\n{text}")
            if not text.endswith("\n"):
                sections.append("\n")
        if package["name"] == "ring":
            headers = {}
            for path in sorted(directory.rglob("*")):
                if path.is_file():
                    header = ring_source_header(path)
                    if header:
                        headers.setdefault(header, []).append(path.relative_to(directory).as_posix())
            if not headers:
                raise RuntimeError("ring per-file source notices were not found")
            for header, sources in headers.items():
                sections.append("\n--- ring source notice in " + ", ".join(sources) + " ---\n" + header + "\n")
    return "".join(sections), len(packages)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the tracked notices need regeneration")
    args = parser.parse_args()
    content, count = render_notices()
    output = ROOT / "THIRD_PARTY_LICENSES.txt"
    if args.check:
        if not output.is_file() or output.read_text(encoding="utf-8") != content:
            parser.error("THIRD_PARTY_LICENSES.txt is stale; run python3 scripts/generate-notices.py")
    else:
        output.write_text(content, encoding="utf-8")
    print(f"{'Checked' if args.check else 'Generated'} Cargo notices for {count} dependency versions")


if __name__ == "__main__":
    main()
